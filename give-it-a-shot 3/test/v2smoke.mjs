// memos
await p.getByRole('button', { name: /Sign it/ }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: /^Veto$/ }).click(); await p.waitForTimeout(300);
await p.getByRole('button', { name: /Sign it/ }).click(); await p.waitForTimeout(300);
await shot('07-memos-done');
