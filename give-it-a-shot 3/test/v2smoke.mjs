console.log('phase', await p.evaluate(() => window.__app.state.g.phase));
await p.getByRole('button', { name: 'Press', exact: true }).click().catch(() => {}); await shot('09-press');
await p.getByRole('button', { name: 'Map', exact: true }).click().catch(() => {}); await shot('10-map');
console.log('errors:', errs.length ? errs.join('\n') : 'none');
await b.close();
